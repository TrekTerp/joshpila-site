import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { readArchive, archiveYears, validateArchive } from './cocktail-data.mjs';
const data=readArchive();
const counts=validateArchive(data);
assert.ok(counts.recipes >= 144);
assert.ok(counts.variants >= 381);
assert.ok(counts.photos >= 129);
assert.ok(counts.days >= 144);
const years=archiveYears(data);
assert.deepEqual(JSON.parse(readFileSync('app/cocktail-years.generated.json','utf8')),years);
const nextYear = Math.max(...years.map(y=>y.year)) + 1;
// A new December must appear from data alone, without editing shelf or calendar code.
const future=structuredClone(data);
future.recipes.push({...future.recipes[0],year:nextYear,slug:'future-test-2027'});
future.daySlots.push({year:nextYear,day:1,official_recipe_slug:'future-test-2027',actual_recipe_slug:null,actual_variant_id:null,actual_recipe_name:null,photo_ids:[]});
validateArchive(future,false);
assert.equal(archiveYears(future)[0].year,nextYear);
assert.equal(archiveYears(future)[0].days,1);
assert.equal(archiveYears(future)[0].status,'Archive');
const partial=structuredClone(data);
partial.years.push({year:nextYear,status:'upcoming'});
assert.equal(archiveYears(partial)[0].status,'Upcoming');
partial.recipes.push({...partial.recipes[0],year:nextYear,slug:'first-2026'});
partial.daySlots.push({...partial.daySlots[0],year:nextYear,day:1,official_recipe_slug:'first-2026',actual_recipe_slug:null,actual_variant_id:null,photo_ids:[]});
assert.equal(archiveYears(partial)[0].status,'Archive');
