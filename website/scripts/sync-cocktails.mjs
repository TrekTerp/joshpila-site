import { copyFileSync } from 'node:fs';
import { mkdirSync, writeFileSync } from 'node:fs';
import { readArchive, archiveYears, validateArchive } from './cocktail-data.mjs';
const data=readArchive();
const counts=validateArchive(data);
const years=archiveYears(data);
mkdirSync('public/cocktails/data',{recursive:true});
const values={RECIPES:data.recipes,PHOTOS:data.photos,DAY_SLOTS:data.daySlots,UMBRELLA_INGREDIENTS:data.umbrellaIngredients,ARCHIVE_YEARS:years};
writeFileSync('public/cocktails/data/data.js','// Generated by npm run sync:cocktails. Edit content/cocktails/archive.json.\n'+Object.entries(values).map(([k,v])=>`window.${k} = ${JSON.stringify(v)};`).join('\n')+'\n');
writeFileSync('app/cocktail-years.generated.json',JSON.stringify(years,null,2)+'\n');
console.log({...counts, years:years.map(y=>y.year)});

copyFileSync('lib/cocktails/import.mjs','public/cocktails/js/import-parser.js');
copyFileSync('lib/cocktails/photos.mjs','public/cocktails/js/photo-selection.js');

copyFileSync('node_modules/@supabase/supabase-js/dist/umd/supabase.js','public/cocktails/js/supabase.js');
copyFileSync('content/cocktails/archive.json','supabase/functions/cocktails/archive.json');
copyFileSync('lib/cocktails/import.mjs','supabase/functions/cocktails/import.mjs');
copyFileSync('lib/cocktails/photos.mjs','supabase/functions/cocktails/photos.mjs');
